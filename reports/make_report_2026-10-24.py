        row = {"n": i + 1, "ep": ep, "cat": cat, "kk": d["qolda_kk"].loc[ep].command_text,
               "en": d["qwen_en"].loc[ep].command_text}
        for key, folder, _ in ARMS:
            out = d[key].loc[ep].outcome
            row[key] = out
            dst = HERE / "video" / folder / f"{i + 1:02d}_{slug}_{ep.replace(':', '_')}_{OUT_TR.get(out, out)}.mp4"
