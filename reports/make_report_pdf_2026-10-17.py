def bullets(items, s=BUL):
    """A bulleted list of paragraphs."""
    return [Paragraph(t, s, bulletText="•") for t in items]


def table(rows, widths, bold_rows=(), caption=None, num_cols=(), font=None, head=None):
    """head: заголовок над таблицей - держится на одной странице с ней (keepWithNext не работает перед KeepTogether)."""
    cell = font or CELL
    cellb = ParagraphStyle("hb", parent=cell, fontName="Arial-Bold")
    cellbr = ParagraphStyle("hbr", parent=cellb, alignment=2)
    cellr = ParagraphStyle("hr", parent=cell, alignment=2)
    data = []
    for i, r in enumerate(rows):
        row = []
        for j, c in enumerate(r):
            if i == 0 or i in bold_rows:
                st = cellbr if j in num_cols else cellb
            else:
                st = cellr if j in num_cols else cell
            row.append(Paragraph(str(c), st))
        data.append(row)
    t = Table(data, colWidths=[w * cm for w in widths], repeatRows=1, hAlign="LEFT")
    t.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, BLACK),
        ("LINEBELOW", (0, 0), (-1, 0), 1.1, BLACK),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 3), ("RIGHTPADDING", (0, 0), (-1, -1), 3),
        ("TOPPADDING", (0, 0), (-1, -1), 1.8), ("BOTTOMPADDING", (0, 0), (-1, -1), 1.8),
    ]))
    out = [t, Paragraph(caption, CAP) if caption else Spacer(1, 6)]
    if head:
        out.insert(0, head if not isinstance(head, str) else Paragraph(head, H2))
    return KeepTogether(out)


def figure(path, width_cm, caption):
    """An image scaled to ``width_cm`` with its caption, kept on one page."""
    from PIL import Image as PILImage
    w, h = PILImage.open(path).size
    img = Image(str(path), width=width_cm * cm, height=width_cm * cm * h / w)
    return KeepTogether([img, Paragraph(caption, CAP)])


